#!/usr/bin/env node
// Regenerates seed.sql and reset.sql from demo/demo-seed-data.json.
//
// The JSON is the single source of truth for the shared WeCPQ+WeSAP demo
// dataset; these two SQL files are always generated from it, never
// hand-edited. Run: npm run seed:gen
//
// WeCPQ's schema (schema.sql): customers, quotes, quote_items. No
// credit_limit on customers (that's WeSAP-only) and quote_items.sku is
// required — both handled below.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const appRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = join(appRoot, "..", "demo", "demo-seed-data.json");
const seedPath = join(appRoot, "seed.sql");
const resetPath = join(appRoot, "reset.sql");

const data = JSON.parse(readFileSync(jsonPath, "utf8"));
const { customers, wecpq } = data;
const { quotes, quote_items: quoteItems } = wecpq;

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlValue(value) {
  return typeof value === "string" ? sqlString(value) : value === null ? "NULL" : value;
}

function insertBlock(comment, table, columns, rows, mapRow) {
  const values = rows.map((row) => `  (${columns.map((c) => sqlValue(mapRow(row)[c])).join(", ")})`).join(",\n");
  return `-- ${comment}\nINSERT INTO ${table} (${columns.join(", ")}) VALUES\n${values};`;
}

const customerColumns = ["id", "name", "ref_id", "industry", "country", "account_owner"];
const customersBlock = insertBlock(
  "Customers (demo-seed-data.json .customers; credit_limit dropped, WeSAP-only)",
  "customers",
  customerColumns,
  customers,
  (c) => c
);

const quoteColumns = ["id", "ref", "customer_id", "vendor", "status", "margin_pct", "subtotal", "total_amount"];
const quotesBlock = insertBlock(
  "Quotes (demo-seed-data.json .wecpq.quotes) — status must satisfy the CHECK enum in schema.sql",
  "quotes",
  quoteColumns,
  quotes,
  (q) => q
);

const itemColumns = ["id", "quote_id", "sku", "description", "quantity", "unit_price", "line_total"];
const itemsBlock = insertBlock(
  "Quote line items (demo-seed-data.json .wecpq.quote_items) — sku is required",
  "quote_items",
  itemColumns,
  quoteItems,
  (i) => i
);

const insertBlocks = [customersBlock, quotesBlock, itemsBlock].join("\n\n");

const seedSql = `-- WeCPQ seed data — generated by scripts/gen-seed.mjs from
-- demo/demo-seed-data.json. Do not hand-edit; run \`npm run seed:gen\` instead.
-- Assumes empty data tables (see reset.sql to wipe + reseed in one step).

${insertBlocks}
`;

const resetSql = `-- WeCPQ data reset — generated by scripts/gen-seed.mjs from
-- demo/demo-seed-data.json. Do not hand-edit; run \`npm run seed:gen\` instead.
-- Data rows only: no DROP/CREATE/ALTER. Idempotent — safe to run repeatedly
-- since IDs/refs are fixed.
--
-- Run against the deployed DB: npm run reset
-- (wrangler d1 execute wecpq --remote --file reset.sql)
--
-- No explicit BEGIN/COMMIT: D1 rejects manual transaction control in SQL
-- ("use state.storage.transaction() ... instead of the SQL BEGIN
-- TRANSACTION or SAVEPOINT statements") and already executes a whole
-- --file as one atomic batch, rolling back on any failure.

PRAGMA defer_foreign_keys=TRUE;

-- Delete children -> parents
DELETE FROM quote_items;
DELETE FROM quotes;
DELETE FROM customers;
DELETE FROM sqlite_sequence;

-- Insert parents -> children (same data as seed.sql)

${insertBlocks}
`;

writeFileSync(seedPath, seedSql);
writeFileSync(resetPath, resetSql);

console.log(`Wrote ${seedPath}`);
console.log(`Wrote ${resetPath}`);
console.log(`customers=${customers.length} quotes=${quotes.length} quote_items=${quoteItems.length}`);
