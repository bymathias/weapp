#!/usr/bin/env node
// Regenerates seed.sql and reset.sql from seed/demo-seed-data.json.
//
// The JSON is the single source of truth for the shared WeCPQ+WeSAP demo
// dataset; these two SQL files are always generated from it, never
// hand-edited. Run: npm run seed:gen
//
// WeSAP's schema (schema.sql) has customers/vendors/materials plus the
// full P2P/O2C document chain. company_code is static config, not demo
// data, and is intentionally left out of both files.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = join(repoRoot, "seed", "demo-seed-data.json");
const seedPath = join(repoRoot, "seed.sql");
const resetPath = join(repoRoot, "reset.sql");

const data = JSON.parse(readFileSync(jsonPath, "utf8"));
const { customers, vendors, materials, wesap } = data;
const {
  sales_orders: salesOrders,
  so_items: soItems,
  deliveries,
  billing_documents: billingDocuments,
  purchase_orders: purchaseOrders,
  po_items: poItems,
  goods_receipts: goodsReceipts,
  gr_items: grItems,
  supplier_invoices: supplierInvoices,
  si_items: siItems,
  payments,
  doc_flow: docFlow,
} = wesap;

function sqlString(value) {
  if (value === null || value === undefined) return "NULL";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlValue(value) {
  return typeof value === "string" ? sqlString(value) : value === null ? "NULL" : value;
}

function insertBlock(comment, table, columns, rows) {
  const values = rows.map((row) => `  (${columns.map((c) => sqlValue(row[c])).join(", ")})`).join(",\n");
  return `-- ${comment}\nINSERT INTO ${table} (${columns.join(", ")}) VALUES\n${values};`;
}

const blocks = [
  insertBlock(
    "Customers — shared with WeCPQ (same id/ref_id) plus credit_limit, WeSAP-only",
    "customers",
    ["id", "name", "ref_id", "industry", "country", "account_owner", "credit_limit"],
    customers
  ),
  insertBlock("Vendors (demo-seed-data.json .vendors)", "vendors", ["id", "name", "ref_id"], vendors),
  insertBlock(
    "Materials (demo-seed-data.json .materials)",
    "materials",
    ["id", "material_code", "description", "vendor_id", "standard_price", "stock_qty"],
    materials
  ),
  insertBlock(
    "Purchase-to-Pay: purchase orders — status must satisfy the CHECK enum in schema.sql",
    "purchase_orders",
    ["id", "po_number", "vendor_id", "status"],
    purchaseOrders
  ),
  insertBlock("Purchase-to-Pay: PO line items", "po_items", ["id", "po_id", "material_id", "qty", "price", "line_total"], poItems),
  insertBlock("Purchase-to-Pay: goods receipts", "goods_receipts", ["id", "gr_number", "po_id", "status"], goodsReceipts),
  insertBlock("Purchase-to-Pay: GR line items", "gr_items", ["id", "gr_id", "po_item_id", "qty_received"], grItems),
  insertBlock(
    "Purchase-to-Pay: supplier invoices — status must satisfy the CHECK enum; block_reason NULL unless Blocked",
    "supplier_invoices",
    ["id", "inv_number", "po_id", "vendor_id", "amount", "status", "block_reason"],
    supplierInvoices
  ),
  insertBlock("Purchase-to-Pay: SI line items", "si_items", ["id", "si_id", "po_item_id", "qty", "price", "line_total"], siItems),
  insertBlock(
    "Order-to-Cash: sales orders — status must satisfy the CHECK enum in schema.sql",
    "sales_orders",
    ["id", "so_number", "customer_id", "status", "source_quote_ref", "total_amount", "customer_po_number"],
    salesOrders
  ),
  insertBlock(
    "Order-to-Cash: SO line items — material_code NULL for non-catalog (services) lines",
    "so_items",
    ["id", "so_id", "description", "qty", "unit_price", "line_total", "material_code"],
    soItems
  ),
  insertBlock("Order-to-Cash: deliveries", "deliveries", ["id", "dlv_number", "so_id", "status"], deliveries),
  insertBlock(
    "Order-to-Cash: billing documents",
    "billing_documents",
    ["id", "bill_number", "so_id", "customer_id", "amount", "status", "customer_po_number"],
    billingDocuments
  ),
  insertBlock(
    "Cross-process: payments",
    "payments",
    ["id", "pay_number", "ref_type", "ref_id", "direction", "amount", "status"],
    payments
  ),
  insertBlock(
    "Cross-process: document flow links",
    "doc_flow",
    ["id", "from_type", "from_id", "to_type", "to_id"],
    docFlow
  ),
];

const insertBlocks = blocks.join("\n\n");

const seedSql = `-- WeSAP seed data — generated by scripts/gen-seed.mjs from
-- seed/demo-seed-data.json. Do not hand-edit; run \`npm run seed:gen\` instead.
-- Assumes empty data tables (see reset.sql to wipe + reseed in one step).
-- company_code is static config, not demo data — seed it separately, once.

${insertBlocks}
`;

const resetSql = `-- WeSAP data reset — generated by scripts/gen-seed.mjs from
-- seed/demo-seed-data.json. Do not hand-edit; run \`npm run seed:gen\` instead.
-- Data rows only: no DROP/CREATE/ALTER. Idempotent — safe to run repeatedly
-- since IDs/refs are fixed. company_code is left untouched (static config,
-- not demo data).
--
-- Run against the deployed DB: npm run reset
-- (wrangler d1 execute wesap --remote --file reset.sql)
--
-- No explicit BEGIN/COMMIT: D1 rejects manual transaction control in SQL
-- ("use state.storage.transaction() ... instead of the SQL BEGIN
-- TRANSACTION or SAVEPOINT statements") and already executes a whole
-- --file as one atomic batch, rolling back on any failure.

PRAGMA defer_foreign_keys=TRUE;

-- Delete children -> parents
DELETE FROM doc_flow;
DELETE FROM payments;
DELETE FROM billing_documents;
DELETE FROM deliveries;
DELETE FROM so_items;
DELETE FROM sales_orders;
DELETE FROM si_items;
DELETE FROM supplier_invoices;
DELETE FROM gr_items;
DELETE FROM goods_receipts;
DELETE FROM po_items;
DELETE FROM purchase_orders;
DELETE FROM materials;
DELETE FROM vendors;
DELETE FROM customers;
DELETE FROM sqlite_sequence;

-- Insert parents -> children (same data as seed.sql)

${insertBlocks}
`;

writeFileSync(seedPath, seedSql);
writeFileSync(resetPath, resetSql);

console.log(`Wrote ${seedPath}`);
console.log(`Wrote ${resetPath}`);
console.log(
  `customers=${customers.length} vendors=${vendors.length} materials=${materials.length} ` +
    `purchase_orders=${purchaseOrders.length} po_items=${poItems.length} goods_receipts=${goodsReceipts.length} ` +
    `gr_items=${grItems.length} supplier_invoices=${supplierInvoices.length} si_items=${siItems.length} ` +
    `sales_orders=${salesOrders.length} so_items=${soItems.length} deliveries=${deliveries.length} ` +
    `billing_documents=${billingDocuments.length} payments=${payments.length} doc_flow=${docFlow.length}`
);
