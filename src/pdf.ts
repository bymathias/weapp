import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { Customer, Material, PurchaseOrderWithItems, SalesOrderWithItems, Vendor } from "./types";

const PAGE_WIDTH = 612; // US Letter
const PAGE_HEIGHT = 792;
const MARGIN = 50;

function money(n: number): string {
  return `$${n.toFixed(2)}`;
}

export async function generatePurchaseOrderPdf(
  po: PurchaseOrderWithItems,
  vendor: Vendor,
  materialsById: Map<number, Material>
): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  let y = PAGE_HEIGHT - MARGIN;

  const draw = (text: string, x: number, opts: { size?: number; f?: typeof font; color?: ReturnType<typeof rgb> } = {}) => {
    page.drawText(text, {
      x,
      y,
      size: opts.size ?? 10,
      font: opts.f ?? font,
      color: opts.color ?? rgb(0.1, 0.1, 0.1),
    });
  };

  // Header / company block
  draw("WeSAP", MARGIN, { size: 22, f: bold, color: rgb(0.039, 0.431, 0.82) });
  draw("Enterprise Resource Planning", MARGIN + 90, { size: 10, color: rgb(0.4, 0.4, 0.4) });
  y -= 16;
  draw("WeSAP AG · Company Code 1000", MARGIN, { size: 9, color: rgb(0.45, 0.45, 0.45) });
  y -= 30;

  page.drawLine({
    start: { x: MARGIN, y },
    end: { x: PAGE_WIDTH - MARGIN, y },
    thickness: 1,
    color: rgb(0.8, 0.8, 0.8),
  });
  y -= 26;

  // PO meta + vendor block, side by side
  const leftX = MARGIN;
  const rightX = PAGE_WIDTH / 2 + 10;
  const topY = y;

  draw("PURCHASE ORDER", leftX, { size: 13, f: bold });
  y -= 16;
  draw(`PO Number: ${po.po_number}`, leftX, { size: 10 });
  y -= 14;
  draw(`Date: ${new Date(po.created_at).toLocaleDateString("en-US")}`, leftX, { size: 10 });
  y -= 14;
  draw(`Status: ${po.status}`, leftX, { size: 10, f: bold });

  y = topY;
  draw("VENDOR", rightX, { size: 13, f: bold });
  y -= 16;
  draw(vendor.name, rightX, { size: 10 });
  y -= 14;
  draw(vendor.ref_id, rightX, { size: 10 });

  y -= 34;

  // Line items table
  const col = {
    desc: MARGIN,
    qty: PAGE_WIDTH - MARGIN - 190,
    unit: PAGE_WIDTH - MARGIN - 130,
    total: PAGE_WIDTH - MARGIN - 60,
  };

  page.drawRectangle({
    x: MARGIN,
    y: y - 4,
    width: PAGE_WIDTH - MARGIN * 2,
    height: 18,
    color: rgb(0.94, 0.95, 0.97),
  });
  draw("Material", col.desc + 4, { size: 9, f: bold });
  draw("Qty", col.qty, { size: 9, f: bold });
  draw("Unit Price", col.unit, { size: 9, f: bold });
  draw("Line Total", col.total, { size: 9, f: bold });
  y -= 22;

  for (const item of po.items) {
    if (y < 140) {
      // Simple one-page demo doc: stop rather than paginate.
      draw("… (additional items omitted)", col.desc + 4, { size: 8, color: rgb(0.5, 0.5, 0.5) });
      y -= 14;
      break;
    }
    const material = materialsById.get(item.material_id);
    const label = material ? `${material.material_code} — ${material.description}` : `Material #${item.material_id}`;
    const desc = label.length > 46 ? `${label.slice(0, 43)}...` : label;
    draw(desc, col.desc + 4, { size: 9 });
    draw(String(item.qty), col.qty, { size: 9 });
    draw(money(item.price), col.unit, { size: 9 });
    draw(money(item.line_total), col.total, { size: 9 });
    y -= 16;
    page.drawLine({
      start: { x: MARGIN, y: y + 6 },
      end: { x: PAGE_WIDTH - MARGIN, y: y + 6 },
      thickness: 0.5,
      color: rgb(0.9, 0.9, 0.9),
    });
  }

  y -= 14;
  page.drawLine({
    start: { x: PAGE_WIDTH / 2, y },
    end: { x: PAGE_WIDTH - MARGIN, y },
    thickness: 1,
    color: rgb(0.8, 0.8, 0.8),
  });
  y -= 20;

  const total = po.items.reduce((s, i) => s + i.line_total, 0);
  const totalsX = PAGE_WIDTH / 2 + 40;
  draw("Total", totalsX, { size: 13, f: bold });
  draw(money(total), col.total, { size: 13, f: bold, color: rgb(0.039, 0.431, 0.82) });

  y = 60;
  page.drawLine({
    start: { x: MARGIN, y: y + 20 },
    end: { x: PAGE_WIDTH - MARGIN, y: y + 20 },
    thickness: 0.5,
    color: rgb(0.9, 0.9, 0.9),
  });
  draw("Generated by WeSAP — this is a demo document.", MARGIN, { size: 8, color: rgb(0.55, 0.55, 0.55) });

  return pdf.save();
}

