import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import type { Customer, QuoteWithItems } from "./types";

const PAGE_WIDTH = 612; // US Letter
const PAGE_HEIGHT = 792;
const MARGIN = 50;

function money(n: number): string {
  return `$${n.toFixed(2)}`;
}

export async function generateQuotePdf(quote: QuoteWithItems, customer: Customer): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([PAGE_WIDTH, PAGE_HEIGHT]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  let y = PAGE_HEIGHT - MARGIN;

  const draw = (text: string, x: number, opts: { size?: number; f?: typeof font; color?: ReturnType<typeof rgb> } = {}) => {
    page.drawText(text, {
      x,
      y,
      size: opts.size ?? 10,
      font: opts.f ?? font,
      color: opts.color ?? rgb(0.1, 0.1, 0.1),
    });
  };

  // Header / company block
  draw("WeCPQ", MARGIN, { size: 22, f: bold, color: rgb(0.12, 0.28, 0.55) });
  draw("Configure · Price · Quote", MARGIN + 90, { size: 10, color: rgb(0.4, 0.4, 0.4) });
  y -= 16;
  draw("WeCPQ Inc. · 100 Market Street · San Francisco, CA", MARGIN, { size: 9, color: rgb(0.45, 0.45, 0.45) });
  y -= 30;

  page.drawLine({
    start: { x: MARGIN, y },
    end: { x: PAGE_WIDTH - MARGIN, y },
    thickness: 1,
    color: rgb(0.8, 0.8, 0.8),
  });
  y -= 26;

  // Quote meta + customer block, side by side
  const leftX = MARGIN;
  const rightX = PAGE_WIDTH / 2 + 10;
  const topY = y;

  draw("QUOTE", leftX, { size: 13, f: bold });
  y -= 16;
  draw(`Ref: ${quote.ref}`, leftX, { size: 10 });
  y -= 14;
  draw(`Date: ${new Date(quote.created_at).toLocaleDateString("en-US")}`, leftX, { size: 10 });
  y -= 14;
  draw(`Status: ${quote.status}`, leftX, { size: 10, f: bold });
  y -= 14;
  draw(`Vendor: ${quote.vendor}`, leftX, { size: 10 });

  y = topY;
  draw("BILL TO", rightX, { size: 13, f: bold });
  y -= 16;
  draw(customer.name, rightX, { size: 10 });
  y -= 14;
  draw(`${customer.ref_id}`, rightX, { size: 10 });
  y -= 14;
  draw(`${customer.industry} · ${customer.country}`, rightX, { size: 10 });
  y -= 14;
  draw(`Account owner: ${customer.account_owner}`, rightX, { size: 10 });

  y -= 34;

  // Line items table
  const col = {
    sku: MARGIN,
    desc: MARGIN + 75,
    qty: PAGE_WIDTH - MARGIN - 190,
    unit: PAGE_WIDTH - MARGIN - 130,
    total: PAGE_WIDTH - MARGIN - 60,
  };

  page.drawRectangle({
    x: MARGIN,
    y: y - 4,
    width: PAGE_WIDTH - MARGIN * 2,
    height: 18,
    color: rgb(0.94, 0.95, 0.97),
  });
  draw("SKU", col.sku + 4, { size: 9, f: bold });
  draw("Description", col.desc, { size: 9, f: bold });
  draw("Qty", col.qty, { size: 9, f: bold });
  draw("Unit Price", col.unit, { size: 9, f: bold });
  draw("Line Total", col.total, { size: 9, f: bold });
  y -= 22;

  for (const item of quote.items) {
    if (y < 140) {
      // Simple one-page demo doc: stop rather than paginate.
      draw("… (additional items omitted)", col.desc, { size: 8, color: rgb(0.5, 0.5, 0.5) });
      y -= 14;
      break;
    }
    const sku = item.sku.length > 14 ? `${item.sku.slice(0, 12)}...` : item.sku;
    const desc = item.description.length > 34 ? `${item.description.slice(0, 31)}...` : item.description;
    draw(sku, col.sku + 4, { size: 9 });
    draw(desc, col.desc, { size: 9 });
    draw(String(item.quantity), col.qty, { size: 9 });
    draw(money(item.unit_price), col.unit, { size: 9 });
    draw(money(item.line_total), col.total, { size: 9 });
    y -= 16;
    page.drawLine({
      start: { x: MARGIN, y: y + 6 },
      end: { x: PAGE_WIDTH - MARGIN, y: y + 6 },
      thickness: 0.5,
      color: rgb(0.9, 0.9, 0.9),
    });
  }

  y -= 14;
  page.drawLine({
    start: { x: PAGE_WIDTH / 2, y },
    end: { x: PAGE_WIDTH - MARGIN, y },
    thickness: 1,
    color: rgb(0.8, 0.8, 0.8),
  });
  y -= 20;

  const totalsX = PAGE_WIDTH / 2 + 40;
  draw("Subtotal", totalsX, { size: 10 });
  draw(money(quote.subtotal), col.total, { size: 10 });
  y -= 16;
  draw(`Margin (${quote.margin_pct}%)`, totalsX, { size: 10 });
  draw(money(quote.total_amount - quote.subtotal), col.total, { size: 10 });
  y -= 18;
  draw("Total", totalsX, { size: 13, f: bold });
  draw(money(quote.total_amount), col.total, { size: 13, f: bold, color: rgb(0.12, 0.28, 0.55) });

  y = 60;
  page.drawLine({
    start: { x: MARGIN, y: y + 20 },
    end: { x: PAGE_WIDTH - MARGIN, y: y + 20 },
    thickness: 0.5,
    color: rgb(0.9, 0.9, 0.9),
  });
  draw("Generated by WeCPQ — this is a demo document.", MARGIN, { size: 8, color: rgb(0.55, 0.55, 0.55) });

  return pdf.save();
}
